ALTER TABLE device_bind
    COMMENT = '设备当前身份、归属和绑定状态',
    MODIFY COLUMN id BIGINT NOT NULL AUTO_INCREMENT COMMENT '设备绑定记录主键',
    MODIFY COLUMN device_id VARCHAR(64) NOT NULL COMMENT '设备业务标识',
    MODIFY COLUMN mac VARCHAR(32) NOT NULL DEFAULT '' COMMENT '设备 MAC 地址',
    MODIFY COLUMN chip_uid VARCHAR(128) NOT NULL DEFAULT '' COMMENT '芯片唯一标识',
    MODIFY COLUMN device_rand VARCHAR(64) NOT NULL DEFAULT '' COMMENT '设备端维护的稳定随机标识',
    MODIFY COLUMN assign VARCHAR(16) NOT NULL DEFAULT '' COMMENT '分配方式：dynamic=设备池分配，preburn=出厂预烧',
    MODIFY COLUMN device_name VARCHAR(64) NOT NULL DEFAULT '' COMMENT '当前绑定用户设置的设备名称，解绑时清空',
    MODIFY COLUMN user_id BIGINT NOT NULL DEFAULT 0 COMMENT '当前绑定用户主键；0 表示未绑定',
    MODIFY COLUMN last_user_id BIGINT NOT NULL DEFAULT 0 COMMENT '最近一次绑定用户主键',
    MODIFY COLUMN active_time DATETIME NULL COMMENT '设备首次或最近激活时间',
    MODIFY COLUMN bind_time DATETIME NULL COMMENT '当前绑定建立时间',
    MODIFY COLUMN unbind_time DATETIME NULL COMMENT '最近一次解绑时间',
    MODIFY COLUMN created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '记录创建时间',
    MODIFY COLUMN updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '最后更新时间',
    MODIFY COLUMN mac_user_key VARCHAR(64) AS (IF(mac='' OR user_id=0, NULL, CONCAT(mac, ':', user_id))) STORED COMMENT '当前用户与 MAC 的唯一约束键';

