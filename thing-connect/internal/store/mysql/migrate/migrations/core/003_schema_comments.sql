-- 为既有业务表补齐 MySQL 元数据注释；字段定义保持与当前 schema 完全一致。
ALTER TABLE schema_migrations
    COMMENT = 'ThingConnect 数据库迁移版本台账',
    MODIFY COLUMN component VARCHAR(64) NOT NULL COMMENT '迁移组件名：core 或 admin',
    MODIFY COLUMN version BIGINT NOT NULL COMMENT '组件迁移版本号',
    MODIFY COLUMN applied_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '迁移完成时间';

ALTER TABLE users
    COMMENT = '业务用户账号',
    MODIFY COLUMN id BIGINT NOT NULL AUTO_INCREMENT COMMENT '用户主键',
    MODIFY COLUMN email VARCHAR(255) NOT NULL COMMENT '登录邮箱，系统内唯一',
    MODIFY COLUMN password VARCHAR(255) NOT NULL COMMENT '密码哈希，不存储明文',
    MODIFY COLUMN bind_quota INT NOT NULL DEFAULT 10 COMMENT '剩余可绑定设备额度',
    MODIFY COLUMN status TINYINT NOT NULL DEFAULT 1 COMMENT '账号状态：1=启用，0=禁用',
    MODIFY COLUMN disabled_at DATETIME NULL COMMENT '账号禁用时间',
    MODIFY COLUMN auth_revision BIGINT NOT NULL DEFAULT 1 COMMENT '认证版本；密码或账号状态变化时递增',
    MODIFY COLUMN created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    MODIFY COLUMN updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '最后更新时间';

