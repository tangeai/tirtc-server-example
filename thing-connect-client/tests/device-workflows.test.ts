import assert from 'node:assert/strict';
import { recognitionPayload, moveScheme, type Scheme } from '../src/domain/recognition.ts';
import { leavePayload, roomPayload } from '../src/domain/room.ts';
import { draftOf, rolePayload, type Role } from '../src/domain/roles.ts';
const a: Scheme = { scheme_id: 'a', scheme_version: 3, name: 'A', output_mode: 'text' };
const b: Scheme = { scheme_id: 'b', scheme_version: 7, name: 'B', output_mode: 'audio' };
assert.deepEqual(recognitionPayload(true, moveScheme([a,b], 1,-1), 12), { enabled: true, schemes: [{ scheme_id:'b',scheme_version:7 },{ scheme_id:'a',scheme_version:3 }], expected_revision:12 });
assert.throws(() => recognitionPayload(true, [], 2));
assert.throws(() => recognitionPayload(true, [a,a], 2));
assert.throws(() => recognitionPayload(false, Array(9).fill(a), 2));
assert.deepEqual(recognitionPayload(false, [], 2).schemes, []);
assert.deepEqual(roomPayload('join','001234','0001'), { room_code:'001234', password:'0001' });
assert.throws(() => roomPayload('join','1234',''));
assert.throws(() => roomPayload('create','','123'));
assert.deepEqual(leavePayload({room_id:'original-room',assignment_version:9,desired_state:'joined',state:'suspended'}),{room_id:'original-room',assignment_version:9});
const role: Role = { id:'own-role',name:'旧名称',region:'sg01',agent_config:{ali_rag:{index_id:'keep'},device_plugins:['plugin'],mcp_tools:['tool']},service_config:{name:'service',type:'coze',config:{app_id:'example',api_key:'fixture-only'}},user_params:{extra:'keep'} };
const draft = draftOf(role); draft.name='新名称';
const payload = rolePayload(role,draft,[]);
assert.equal(payload.name,'新名称');
assert.deepEqual(payload.service_config,role.service_config);
assert.deepEqual(payload.agent_config?.ali_rag,role.agent_config?.ali_rag);
assert.deepEqual(payload.agent_config?.mcp_tools,['tool']);
assert.deepEqual(payload.agent_config?.device_plugins,['plugin']);
assert.equal(payload.user_params?.extra,'keep');
assert.equal(payload.region,undefined);
assert.throws(() => rolePayload(role,{...draft,name:''},[]));
